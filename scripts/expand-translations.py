    for lang_code, new_translations in TRANSLATIONS.items():
        filepath = TRANSLATIONS_DIR / f"{lang_code}.json"
        
        # Carica esistente
        if filepath.exists():
            existing = json.loads(filepath.read_text(encoding="utf-8"))
        else:
            existing = {}
        
        # Merge: nuove traduzioni sovrascrivono esistenti
        before_count = len(existing)
        existing.update(new_translations)
        after_count = len(existing)
        
        # Salva
        filepath.write_text(json.dumps(existing, ensure_ascii=False, indent=None, separators=(",", ":")), encoding="utf-8")
        print(f"[OK] {lang_code}.json: {before_count} → {after_count} traduzioni (+{after_count-before_count})")
    
    print()
